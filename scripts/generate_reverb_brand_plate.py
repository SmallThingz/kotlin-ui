#!/usr/bin/env python3
"""Alias the fixed AMOLED foreground and export dark ink and compact raw icon grain."""

import argparse
from pathlib import Path
import re
import struct
import zlib


ROOT = Path(__file__).resolve().parents[1]
KOTLIN = "src/main/kotlin/smallthingz/ui"
SOURCE_FILES = tuple(f"{KOTLIN}/{name}.kt" for name in (
    "components/NativeColorScheme",
    "components/NativeDarkSurfaceRecipe",
    "components/NativeDarkSurfacePreset",
    "components/NativeDefaultColorScheme",
    "graphics/ProceduralNoise",
))
ICON_TILE_SIZE = 64
XML = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate_reverb_brand_plate.py. -->\n'
ANDROID = "http://schemas.android.com/apk/res/android"


def require_pattern(pattern, source):
    match = re.search(pattern, source, re.MULTILINE)
    if match is None:
        raise ValueError(f"Shared paint contract changed; update the export: {pattern}")
    return match


def exported_colors(scheme, recipe, preset, defaults):
    require_pattern(r"val ink: Int get\(\) = onSurface", scheme)
    require_pattern(r"darkColors = NativeDarkSurfacePreset\.Amoled\.colorScheme\(\)", defaults)
    require_pattern(r"val Amoled = NativeDarkSurfacePreset\(NativeDarkSurfaces\.AMOLED,[^)]*"
                    r"foregroundGrain = NativeDarkSurfaceRecipe\.amoledForegroundGrain", preset)
    intensity = require_pattern(r"const val amoledForegroundGrain = (\d*\.?\d+)f", recipe)[1]
    dark_fill = "@color/native_amoled_foreground_fill"

    def fallback(block, role):
        return "#" + require_pattern(rf"^\s*{role} = 0xFF([\dA-F]{{6}})\.toInt\(\),", block)[1]

    def system(block, role):
        name = require_pattern(rf"^\s*{role} = readColor\(android\.R\.color\.(\w+)\),", block)[1]
        return f"@android:color/{name}"

    dark_fallback = scheme.split("private val DARK = ", 1)[1]
    api34, api31 = scheme.split("private fun dynamic34(", 1)[1].split("private fun dynamic31(", 1)
    day_branch = ") else NativeColorScheme.fallback(false).copy("
    night34, _ = api34.split(day_branch, 1)
    night31, _ = api31.split(day_branch, 1)
    fallback_colors = (dark_fill, fallback(dark_fallback, "onSurface"), fallback(dark_fallback, "primary"))
    colors = {
        "values": fallback_colors,
        "values-night": fallback_colors,
    }
    for sdk, night in ((31, night31), (34, night34)):
        dark_colors = (dark_fill, system(night, "onSurface"), system(night, "primary"))
        colors[f"values-v{sdk}"] = dark_colors
        colors[f"values-night-v{sdk}"] = dark_colors
    return colors, str(float(intensity))


def grain_png(source):
    """Read the small xorshift sampler grammar from the Kotlin owner; changes fail closed."""
    period = int(require_pattern(r"^const val NOISE_TILE_SIZE = (\d+)", source)[1])
    seed = int(require_pattern(r"^private const val NOISE_SEED = (0x[\dA-Fa-f]+)", source)[1], 16)
    sampler = require_pattern(
        r"private fun fillNoisePixels\(pixels: IntArray, initialState: Int\): Int \{\s*"
        r"var state = initialState\s*for \(index in pixels.indices\) \{\s*"
        r"((?:state = state xor \(state (?:shl|ushr) \d+\)\s*)+)"
        r"val sample = \(state ushr (\d+)\) % (\d+)\s*"
        r"val alpha = (\d+) \+ sample % (\d+)\s*"
        r"pixels\[index\] = \(alpha shl 24\) or \(if \(sample < (\d+)\) 0 else (0x[\da-fA-F]+)\)\s*"
        r"\}\s*return state\s*\}", source)
    shifts = [(operation, int(bits)) for operation, bits in re.findall(r"(shl|ushr) (\d+)", sampler[1])]
    sample_shift, samples, min_alpha, alpha_period, black_samples = map(int, sampler.groups()[1:6])
    white = int(sampler[7], 16)
    if not 1 <= ICON_TILE_SIZE <= period or white != 0xFFFFFF:
        raise ValueError("The brand export requires a grayscale crop of the shared grain")

    rows = bytearray()
    state = seed
    for _ in range(ICON_TILE_SIZE):
        rows.append(0)  # PNG scanline with no filtering.
        for x in range(period):
            for operation, bits in shifts:
                state ^= (state << bits) & 0xFFFFFFFF if operation == "shl" else state >> bits
            if x < ICON_TILE_SIZE:
                sample = (state >> sample_shift) % samples
                rows.extend((0 if sample < black_samples else 255, min_alpha + sample % alpha_period))

    def chunk(kind, data):
        return struct.pack("!I", len(data)) + kind + data + struct.pack("!I", zlib.crc32(kind + data))

    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack("!IIBBBBB", ICON_TILE_SIZE, ICON_TILE_SIZE, 8, 4, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(rows, 9))
            + chunk(b"IEND", b""))


def outputs():
    *palette_sources, noise_source = [(ROOT / path).read_text(encoding="utf-8") for path in SOURCE_FILES]
    colors, intensity = exported_colors(*palette_sources)
    output = {}
    roles = ("reverb_brand_surface", "reverb_brand_surface_main", "reverb_brand_surface_accent")
    for qualifier, values in colors.items():
        definitions = "".join(f'    <color name="{role}">{value}</color>\n' for role, value in zip(roles, values))
        output[f"src/main/res/{qualifier}/reverb_brand_surface.xml"] = (XML + f"<resources>\n{definitions}</resources>\n").encode()
    bitmap = 'android:src="@drawable/reverb_brand_grain_tile" android:tileMode="repeat" android:filter="false" android:dither="true"'
    output["src/main/res/drawable-nodpi/reverb_brand_grain_tile.png"] = grain_png(noise_source)
    output["src/main/res/drawable/reverb_brand_grain.xml"] = (XML + f'<bitmap xmlns:android="{ANDROID}"\n    {bitmap} />\n').encode()
    output["src/main/res/drawable/reverb_brand_plate.xml"] = (XML + f'''<layer-list xmlns:android="{ANDROID}">
    <item android:drawable="@color/reverb_brand_surface" />
    <item>
        <bitmap {bitmap}
            android:alpha="{intensity}" />
    </item>
</layer-list>
''').encode()
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    changed = []
    for name, data in outputs().items():
        path = ROOT / name
        if path.is_file() and path.read_bytes() == data:
            continue
        changed.append(name)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if args.check and changed:
        raise SystemExit("Regenerate the shared Reverb plate: " + ", ".join(changed))
    print(f"{'Updated ' + str(len(changed)) if changed else 'All'} shared Reverb plate resources match their sources")


if __name__ == "__main__":
    main()
